CREATE TABLE IF NOT EXISTS `audit_logs` (
  `id` INT(10) UNSIGNED NOT NULL AUTO_INCREMENT,
  `user_id` INT(10) UNSIGNED DEFAULT NULL,
  `action` VARCHAR(100) DEFAULT NULL,
  `table_name` VARCHAR(100) DEFAULT NULL,
  `record_id` INT(10) UNSIGNED DEFAULT NULL,
  `old_values` LONGTEXT DEFAULT NULL,
  `new_values` LONGTEXT DEFAULT NULL,
  `module_name` VARCHAR(100) DEFAULT NULL,
  `record_type` VARCHAR(100) DEFAULT NULL,
  `action_name` VARCHAR(100) DEFAULT NULL,
  `description` LONGTEXT DEFAULT NULL,
  `ip_address` VARCHAR(50) DEFAULT NULL,
  `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`)
);

INSERT INTO `audit_logs` (`id`, `user_id`, `action`, `table_name`, `record_id`, `description`, `ip_address`, `created_at`)
SELECT al.`id`, al.`user_id`, al.`action`, al.`module`, al.`reference_id`, al.`details`, al.`ip_address`, al.`created_at`
FROM `audit_log` al
WHERE NOT EXISTS (
  SELECT 1 FROM `audit_logs` x WHERE x.`id` = al.`id`
);
