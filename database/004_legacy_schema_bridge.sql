USE `spamsdb`;

ALTER TABLE `roles`
  ADD COLUMN IF NOT EXISTS `name` VARCHAR(100) DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS `description` VARCHAR(255) DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS `is_active` TINYINT(1) NOT NULL DEFAULT 1,
  ADD COLUMN IF NOT EXISTS `updated_at` DATETIME NULL DEFAULT NULL;

UPDATE `roles`
SET `name` = `role_name`
WHERE (`name` IS NULL OR `name` = '')
  AND `role_name` IS NOT NULL;

ALTER TABLE `users`
  ADD COLUMN IF NOT EXISTS `employee_id` INT(10) UNSIGNED DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS `office_id` INT(10) UNSIGNED DEFAULT NULL;

ALTER TABLE `departments`
  ADD COLUMN IF NOT EXISTS `description` VARCHAR(255) DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS `created_by` INT(10) UNSIGNED DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS `updated_by` INT(10) UNSIGNED DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS `updated_at` DATETIME NULL DEFAULT NULL;

ALTER TABLE `employees`
  ADD COLUMN IF NOT EXISTS `email` VARCHAR(150) DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS `department_id` INT(10) UNSIGNED DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS `responsibility_code_id` INT(10) UNSIGNED DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS `employment_status` VARCHAR(50) DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS `is_unit_head` TINYINT(1) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS `created_by` INT(10) UNSIGNED DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS `updated_by` INT(10) UNSIGNED DEFAULT NULL;

ALTER TABLE `offices`
  ADD COLUMN IF NOT EXISTS `office_head_employee_id` INT(10) UNSIGNED DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS `description` VARCHAR(255) DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS `created_by` INT(10) UNSIGNED DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS `updated_by` INT(10) UNSIGNED DEFAULT NULL;

UPDATE `offices`
SET `office_head_employee_id` = `head_employee_id`
WHERE `office_head_employee_id` IS NULL
  AND `head_employee_id` IS NOT NULL;

ALTER TABLE `responsibility_codes`
  ADD COLUMN IF NOT EXISTS `updated_by` INT(10) UNSIGNED DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS `created_by` INT(10) UNSIGNED DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS `updated_at` DATETIME NULL DEFAULT NULL;

ALTER TABLE `suppliers`
  ADD COLUMN IF NOT EXISTS `tin_no` VARCHAR(50) DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS `created_by` INT(10) UNSIGNED DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS `updated_by` INT(10) UNSIGNED DEFAULT NULL;

UPDATE `suppliers`
SET `tin_no` = `tin`
WHERE (`tin_no` IS NULL OR `tin_no` = '')
  AND `tin` IS NOT NULL;

ALTER TABLE `funds`
